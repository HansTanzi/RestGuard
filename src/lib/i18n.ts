// 更新文档的 lang 和书写方向，让浏览器选对字形（中日韩汉字）并让阿拉伯语从右到左排版
export function applyDocumentLang(lang: UiLang) {
  const el = document.documentElement;
  el.lang = lang === "zh" ? "zh-CN" : lang;
  el.dir = lang === "ar" ? "rtl" : "ltr";
}

